const (
	// CoordinatorDriverName is the fixed identifier used in topology coordinator
	// DeviceClass labels and annotations. The DRA driver name in opaque config
	// is configurable through --driver-name.
	CoordinatorDriverName = "nodepartition.dra.k8s.io"
)

// CouplingLevel indicates the topology tightness of a partition's constraints.
type CouplingLevel string

const (
	// CouplingTight means the partition's devices share a PCIe root (same switch).
	CouplingTight CouplingLevel = "tight"
	// CouplingLoose means the partition's devices share a NUMA node but not a PCIe root.
	CouplingLoose CouplingLevel = "loose"
	// CouplingNone means no cross-driver coupling constraint was applied.
	CouplingNone CouplingLevel = ""
)

// PartitionConfig is the opaque configuration embedded in DeviceClass config.
// It tells the webhook how to expand a partition claim into sub-resource requests.
type PartitionConfig struct {
	Kind string `json:"kind"`
	// Mode identifies whether this catalog offering is container-safe or
	// explicitly intended for VM passthrough.
	Mode         OfferingMode        `json:"mode,omitempty"`
	SubResources []SubResourceConfig `json:"subResources"`
	Alignments   []AlignmentConfig   `json:"alignments"`
}

// SubResourceConfig defines a sub-resource that a partition contains.
type SubResourceConfig struct {
	// SourceDriver identifies the driver used for topology satisfiability checks.
	// It may differ from DeviceClass when a mode-specific class is requested.
	SourceDriver string `json:"sourceDriver,omitempty"`
	DeviceClass  string `json:"deviceClass"`
	Count        int    `json:"count"`
	// Passthrough marks this subresource for VM passthrough handling when the
	// enclosing offering is in passthrough mode.
	Passthrough bool `json:"passthrough,omitempty"`
	// Capacity specifies consumable capacity requests for shared devices.
	// When set, the device is shared via DRAConsumableCapacity instead of
	// exclusive allocation. The key is the capacity name (e.g., "dra.cpu/cpu"),
	// the value is the quantity string (e.g., "16").
	Capacity map[string]string `json:"capacity,omitempty"`
	// Selectors contains CEL expressions that pin this sub-resource to specific
	// topology attributes. Generated by the coordinator from topology rules so
	// each driver's devices are constrained using the driver's own attribute
	// namespace (e.g., device.attributes["gpu.amd.com"].numaNode == 0).
	Selectors []string `json:"selectors,omitempty"`
	// PartitionMode indicates the DRA partition mode for this sub-resource.
	// When set, the webhook adds a CEL selector to filter by partition type
	// (e.g., "SPX" for full GPU, "DPX" for half, "CPX" for eighth).
	PartitionMode string `json:"partitionMode,omitempty"`
	// Opaque is an explicit driver-owned configuration copied to the matching
	// expanded request. The coordinator does not interpret its parameters.
	Opaque *OpaqueConfig `json:"opaque,omitempty"`
}

// Validate checks the coordinator-owned portions of a partition contract.
// Driver-specific opaque parameters are intentionally not interpreted here.
func (c *PartitionConfig) Validate() error {
	if c == nil {
		return fmt.Errorf("partition config is nil")
	}
	if c.Kind != "PartitionConfig" {
		return fmt.Errorf("kind must be PartitionConfig")
	}
	if c.Mode != "" && c.Mode != OfferingModeContainer && c.Mode != OfferingModePassthrough {
		return fmt.Errorf("invalid mode %q", c.Mode)
	}
	if len(c.SubResources) == 0 {
		return fmt.Errorf("subResources must not be empty")
	}
	seenClasses := make(map[string]struct{}, len(c.SubResources))
	alignable := make(map[string]struct{}, 2*len(c.SubResources))
	for i, sr := range c.SubResources {
		if sr.DeviceClass == "" {
			return fmt.Errorf("subResources[%d] missing deviceClass", i)
		}
		if _, exists := seenClasses[sr.DeviceClass]; exists {
			return fmt.Errorf("subResources[%d] has duplicate deviceClass %q", i, sr.DeviceClass)
		}
		seenClasses[sr.DeviceClass] = struct{}{}
		// Classes published before alignments used DeviceClass names
		// referenced the source driver instead; accept both until they are rewritten.
		if sr.SourceDriver != "" {
			alignable[sr.SourceDriver] = struct{}{}
		}
		alignable[sr.DeviceClass] = struct{}{}
		if sr.Count < 1 {
			return fmt.Errorf("subResources[%d] count must be positive", i)
		}
		if sr.Opaque == nil {
			continue
		}
		if err := sr.Opaque.validate(); err != nil {
			return fmt.Errorf("subResources[%d] %w", i, err)
		}
		if c.Mode != OfferingModePassthrough || !sr.Passthrough {
			return fmt.Errorf("subResources[%d] opaque config requires passthrough mode and passthrough=true", i)
		}
	}
	for i, alignment := range c.Alignments {
		if alignment.Attribute == "" {
			return fmt.Errorf("alignments[%d] missing attribute", i)
		}
		for _, request := range alignment.Requests {
			if _, exists := alignable[request]; !exists {
				return fmt.Errorf("alignments[%d] references unknown deviceClass %q", i, request)
			}
		}
	}
	return nil
}

// AlignmentConfig defines a matchAttribute constraint for the combined claim.
type AlignmentConfig struct {
	Attribute   string          `json:"attribute"`
	Requests    []string        `json:"requests"`
	Enforcement EnforcementMode `json:"enforcement"`
}

// sortPartitionConfig normalizes a PartitionConfig's ordering so that the
// marshaled JSON (and therefore the opaque DeviceClass config) is stable
// across reconciles. SubResources and Alignments[].Requests are built by
// ranging maps (DeviceCounts), which iterate in random order in Go; without
// this, publishDeviceClass would see a spurious diff on every reconcile and
// its no-op short-circuit would never fire.
func sortPartitionConfig(config *PartitionConfig) {
	sort.Slice(config.SubResources, func(i, j int) bool {
		a, b := config.SubResources[i], config.SubResources[j]
		if a.DeviceClass != b.DeviceClass {
			return a.DeviceClass < b.DeviceClass
		}
		return a.Count < b.Count
	})
	for i := range config.Alignments {
		sort.Strings(config.Alignments[i].Requests)
	}
	// Alignments themselves are appended in topology-rule order, which comes
	// from TopologyRuleStore ranging over a map (random order). Sort them too
	// so the marshaled config is stable when 2+ match-constraint rules exist.
	sort.Slice(config.Alignments, func(i, j int) bool {
		a, b := config.Alignments[i], config.Alignments[j]
		if a.Attribute != b.Attribute {
			return a.Attribute < b.Attribute
		}
		return strings.Join(a.Requests, ",") < strings.Join(b.Requests, ",")
	})
}

// mergeMinCapacity reduces two capacity maps to the per-key minimum over the
// keys they share, which is the only value guaranteed satisfiable on every
// alternative in an aggregate.
//
// Aggregates intersect device counts (a driver must be present on every
// instance, at the minimum count); capacity needs the same treatment for the
// same reason. PCIe-root partitions in particular can carry genuinely
// different capacities for the same driver, because the builder divides a
// shared device's capacity by the number of PCIe roots on its NUMA node
// (partition_builder.go, divideQuantity) - a node whose NUMA nodes have
// different root counts yields partitions with different per-partition
// capacity under one aggregate key.
//
// Taking the minimum is both deterministic (the previous last-writer-wins
// assignment varied with map iteration order, so the published config, and
// therefore publishDeviceClass's no-op check, changed between reconciles)
// and safe (advertising the larger value produces claims unschedulable on
// the smaller partition).
//
// A key absent from either side is dropped: a capacity that is not present
// on every alternative cannot be guaranteed by the aggregate. A key whose
// value fails to parse as a Kubernetes quantity on either side is dropped
// for the same reason: there is no trustworthy minimum to compare against,
// and guessing one (e.g. by lexical string order) can silently pick the
// numerically larger value, which is exactly what this function exists to
// prevent.
func mergeMinCapacity(existing, incoming map[string]string) map[string]string {
	if existing == nil || incoming == nil {
		return nil
	}
	merged := make(map[string]string, len(existing))
	for name, have := range existing {
		next, ok := incoming[name]
		if !ok {
			continue // not guaranteed across all alternatives
		}
		min, ok := minQuantityString(have, next)
		if !ok {
			continue // unparseable value has no trustworthy minimum
		}
		merged[name] = min
	}
	if len(merged) == 0 {
		return nil
	}
	return merged
}

// minQuantityString returns the smaller of two Kubernetes quantity strings
// and true, or ("", false) if either fails to parse. Unlike a generic
// comparator, it deliberately has no fallback for unparseable input: a
// lexical comparison of quantity strings has no relationship to their
// numeric value (e.g. "16" sorts before "8"), so guessing would risk
// silently selecting the larger, unsafe value instead of failing visibly.
func minQuantityString(a, b string) (string, bool) {
	qa, errA := resource.ParseQuantity(a)
	qb, errB := resource.ParseQuantity(b)
	if errA != nil || errB != nil {
		klog.V(4).Infof("Capacity value not parseable as a quantity (%q, %q); dropping from aggregate", a, b)
		return "", false
	}
	if qb.Cmp(qa) < 0 {
		return b, true
	}
	return a, true
}

// deviceIntersectionState accumulates per-driver device counts, capacity,
// and devices across repeated instances sharing an aggregate key (a
// partition type, or a grouping name), and reduces them to the intersection:
// a driver survives only if present on every added instance, at the minimum
// count and minimum capacity across those instances.
//
// Shared by SyncDeviceClasses' partition-type aggregate and
// SyncGroupingDeviceClasses' grouping aggregate, which both need this exact
// reduction for the same reason: an aggregate DeviceClass must describe only
// what's guaranteed across every alternative it could resolve to, never one
// arbitrary alternative's full capability (see the comments at each call
// site for why that matters).
type deviceIntersectionState struct {
	driverSeen map[string]int // driver -> number of instances that have it
	minCounts  map[string]int
	minCap     map[string]map[string]string
	devices    []TopologyDevice
	total      int // number of instances added
}

func newDeviceIntersectionState() *deviceIntersectionState {
	return &deviceIntersectionState{
		driverSeen: make(map[string]int),
		minCounts:  make(map[string]int),
		minCap:     make(map[string]map[string]string),
	}
}

// add folds one instance's device counts, capacity, and devices into the
// accumulator.
func (s *deviceIntersectionState) add(counts map[string]int, capacity map[string]map[string]string, devices []TopologyDevice) {
	s.total++
	for driver, count := range counts {
		// Capture how many times this driver has been added *before* this
		// call: this, not presence in s.minCap, is what distinguishes "never
		// seen" from "seen, and its capacity was already dropped because an
		// earlier instance lacked it." Using map presence for that check was
		// the bug: once a capacity entry is deleted mid-fold, the next
		// instance that happens to declare the same capacity looks
		// indistinguishable from a true first occurrence and silently
		// resurrects a guarantee that one of the alternatives already broke.
		seenBefore := s.driverSeen[driver]
		s.driverSeen[driver]++
		if prev, has := s.minCounts[driver]; !has || count < prev {
			s.minCounts[driver] = count
		}
		cap, hasCap := capacity[driver]
		switch {
		case seenBefore == 0:
			// True first occurrence: capacity is only ever guaranteed if
			// every occurrence declares it, starting here.
			if hasCap {
				s.minCap[driver] = cap
			}
		case s.minCap[driver] != nil:
			if merged := mergeMinCapacity(s.minCap[driver], cap); merged != nil {
				s.minCap[driver] = merged
			} else {
				delete(s.minCap, driver)
			}
		default:
			// Already permanently dropped by an earlier occurrence (either
			// the first one lacked capacity, or a later merge found a gap).
			// Stay dropped - a later occurrence declaring this driver's
			// capacity again must not resurrect a broken guarantee.
		}
	}
	s.devices = append(s.devices, devices...)
}

// intersect returns the counts and capacity for drivers present on every
// added instance, at the minimum count/capacity. extra, if non-nil, is
// consulted for drivers that did not survive the plain intersection, to
// support carve-outs like the partition path's SLIT-reachability check; it
// returns the count to use and whether the driver should be included.
func (s *deviceIntersectionState) intersect(extra func(driver string) (count int, ok bool)) (map[string]int, map[string]map[string]string) {
	counts := make(map[string]int)
	cap := make(map[string]map[string]string)
	for driver, seenCount := range s.driverSeen {
		if seenCount == s.total {
			counts[driver] = s.minCounts[driver]
			if c, ok := s.minCap[driver]; ok {
				cap[driver] = c
			}
			continue
		}
		if extra == nil {
			continue
		}
		if count, ok := extra(driver); ok {
			counts[driver] = count
			if c, ok := s.minCap[driver]; ok {
				cap[driver] = c
			}
		}
	}
	return counts, cap
}

// profilePartition tracks a unique partition instance for DeviceClass generation.
type profilePartition struct {
	profile        string
	partType       PartitionType
	representative PartitionDevice
	cachedConfig   PartitionConfig
	cachedCoupling CouplingLevel
	count          int
}

// aggregateKey groups partitions by profile and type for aggregate DeviceClasses.
type aggregateKey struct {
	profile  string
	partType PartitionType
}

// DeviceClassManager creates and manages DeviceClass objects based on discovered partition types.
type DeviceClassManager struct {
	client     kubernetes.Interface
	driverName string
	rules      *TopologyRuleStore
}

// NewDeviceClassManager creates a new DeviceClassManager.
func NewDeviceClassManager(client kubernetes.Interface, driverName string, rules *TopologyRuleStore) *DeviceClassManager {
	if driverName == "" {
		driverName = CoordinatorDriverName
	}
	return &DeviceClassManager{
		client:     client,
		driverName: driverName,
		rules:      rules,
	}
}

// SyncDeviceClasses creates or updates DeviceClass objects for each partition type
// discovered across all nodes.
func (m *DeviceClassManager) SyncDeviceClasses(ctx context.Context, results []PartitionResult) error {
	// Errors are accumulated rather than returned immediately so that one
	// unpublishable DeviceClass does not block every other DeviceClass from
	// reconciling (same rationale as SyncGroupingDeviceClasses).
	var publishErrs []error

	// Collect all unique partition types and their profiles.
	// Cache the partition config to avoid computing it twice (once for key, once for DeviceClass).
	seen := make(map[string]*profilePartition)
	for _, result := range results {
		for _, partition := range result.Partitions {
			// Compute partition config and coupling level once.
			config, coupling := m.buildPartitionConfig(partition.Type, partition)
			key := truncateLabel(result.Profile) + "-" + string(partition.Type)
			if len(partition.NUMANodes) > 0 && partition.Type != PartitionFull {
				key += numaKeySuffix(partition.NUMANodes)
			}
			if partition.Type == PartitionPCIeRoot && len(partition.PCIeRoots) > 0 {
				// Keep the raw root in the identity key. Published names are
				// sanitized separately, so normalization collisions can be rejected
				// instead of silently merging distinct partitions.
				key += "-" + partition.PCIeRoots[0]
			}
			if coupling != CouplingNone {
				key += "-" + string(coupling)
			}
			if pp, ok := seen[key]; ok {
				pp.count++
			} else {
				seen[key] = &profilePartition{
					profile:        result.Profile,
					partType:       partition.Type,
					representative: partition,
					cachedConfig:   config,
					cachedCoupling: coupling,
					count:          1,
				}
			}
		}
	}

	// Fixed PCIe partition classes also stopped using the reserved -railN
	// naming. Hold the old class in place until an operator removes it, so an
	// upgrade cannot delete a class still referenced by claims.
	classes, err := m.client.ResourceV1().DeviceClasses().List(ctx, metav1.ListOptions{
		LabelSelector: fmt.Sprintf("%s/managed=true,%s/partitionType", CoordinatorDriverName, CoordinatorDriverName),
	})
	if err != nil {
		return fmt.Errorf("failed to check legacy partition DeviceClasses: %w", err)
	}
	for _, dc := range classes.Items {
		if dc.Labels[CoordinatorDriverName+"/partitionType"] == string(PartitionPCIeRoot) &&
			dc.Labels[CoordinatorDriverName+"/railIndex"] != "" {
			return fmt.Errorf("legacy fixed-partition rail DeviceClass %q requires migration; remove it before publishing topology-specific names", dc.Name)
		}
	}

	pcieClassOwners := make(map[string]string)
	for key, pp := range seen {
		if pp.partType != PartitionPCIeRoot {
			continue
		}
		candidate := m.buildDeviceClassFromCache(pp.profile, pp.partType, pp.representative, pp.cachedConfig, pp.cachedCoupling, pp.count)
		if owner, exists := pcieClassOwners[candidate.Name]; exists && owner != key {
			return fmt.Errorf("PCIe-root DeviceClass name collision: %q represents distinct topology roots", candidate.Name)
		}
		pcieClassOwners[candidate.Name] = key
	}

	// Create/update a DeviceClass for each profile+partitionType
	activeNames := make(map[string]bool, len(seen))
	for _, pp := range seen {
		dc := m.buildDeviceClassFromCache(pp.profile, pp.partType, pp.representative, pp.cachedConfig, pp.cachedCoupling, pp.count)
		if pp.partType == PartitionFull {
			dc.Name = string(PartitionFull)
		}
		activeNames[dc.Name] = true
		if err := m.publishDeviceClass(ctx, dc); err != nil {
			publishErrs = append(publishErrs, fmt.Errorf("failed to publish DeviceClass %s: %w", dc.Name, err))
		}
	}

	// Emit aggregate DeviceClasses per partition type (pcieroot, numa).
	// No NUMA/PCIe selectors — the scheduler picks placement.
	// Use intersection of device counts: only include drivers present on
	// ALL partitions of the same type. This ensures the aggregate is
	// schedulable on any instance. Asymmetric devices (NICs on some roots
	// but not others) are handled via grouping DeviceClasses instead.
	type aggregateState struct {
		profile        string
		partType       PartitionType
		acc            *deviceIntersectionState
		partitionNUMAs []int64 // primary NUMA node of each partition
		count          int     // sum of pp.count
	}
	aggStates := make(map[aggregateKey]*aggregateState)
	for _, pp := range seen {
		if pp.partType == PartitionFull {
			continue
		}
		ak := aggregateKey{profile: pp.profile, partType: pp.partType}
		state, ok := aggStates[ak]
		if !ok {
			state = &aggregateState{
				profile:  pp.profile,
				partType: pp.partType,
				acc:      newDeviceIntersectionState(),
			}
			aggStates[ak] = state
		}
		state.count += pp.count
		if len(pp.representative.NUMANodes) > 0 {
			state.partitionNUMAs = append(state.partitionNUMAs, pp.representative.NUMANodes[0])
		}
		state.acc.add(pp.representative.DeviceCounts, pp.representative.DeviceCapacity, pp.representative.Devices)
	}
	aggregates := make(map[aggregateKey]*profilePartition)
	for ak, state := range aggStates {
		// Intersection: keep drivers present on all partitions, or reachable
		// to all partitions via SLIT-distance NUMANodes lists.
		intersectedCounts, intersectedCap := state.acc.intersect(func(driver string) (int, bool) {
			if ak.partType != PartitionNUMA || !isDriverReachableToAll(driver, state.partitionNUMAs, state.acc.devices) {
				return 0, false
			}
			// SLIT-reachable driver: divide total count by the number of
			// NUMA nodes sharing access to get the per-partition share.
			sharingNUMAs := countSharingNUMAs(driver, state.partitionNUMAs, state.acc.devices)
			count := state.acc.minCounts[driver]
			if sharingNUMAs > 1 {
				count = count / sharingNUMAs
			}
			if count < 1 {
				count = 1
			}
			return count, true
		})
		mergedRep := PartitionDevice{
			Profile:        state.profile,
			Type:           state.partType,
			DeviceCounts:   intersectedCounts,
			DeviceCapacity: intersectedCap,
			Devices:        state.acc.devices,
		}
		aggConfig, aggCoupling := m.buildPartitionAggregateConfig(mergedRep)
		aggregates[ak] = &profilePartition{
			profile:        state.profile,
			partType:       state.partType,
			representative: mergedRep,
			cachedConfig:   aggConfig,
			cachedCoupling: aggCoupling,
			count:          state.count,
		}
	}
	for _, pp := range aggregates {
		dc := m.buildDeviceClassFromCache(pp.profile, pp.partType, pp.representative, pp.cachedConfig, CouplingNone, pp.count)
		dc.Name = string(pp.partType)
		activeNames[dc.Name] = true
		if err := m.publishDeviceClass(ctx, dc); err != nil {
			publishErrs = append(publishErrs, fmt.Errorf("failed to publish aggregate DeviceClass %s: %w", dc.Name, err))
		}
	}

	// Emit tier-named aggregate DeviceClasses (eighth, quarter, half, etc.)
	// based on the fraction of total PCIe roots each partition type covers.
	// Collect all partitions for countPCIeRootsInNUMA lookups.
	var allPartitions []PartitionDevice
	for _, result := range results {
		allPartitions = append(allPartitions, result.Partitions...)
	}
	pcieRootCount := 0
	for _, pp := range seen {
		if pp.partType == PartitionPCIeRoot {
			pcieRootCount++
		}
	}

	// Compute tier names for partition types that map to a fraction of PCIe
	// roots. For pcieroot partitions: 1/N of total roots. For NUMA partitions:
	// count PCIe roots in the NUMA node / total roots (e.g., 4/8 = half).
	tierNames := make(map[aggregateKey]string)
	if pcieRootCount > 0 {
		for ak, pp := range aggregates {
			tierName := computeTierName(ak.partType, pp, allPartitions, ak.profile, pcieRootCount)
			if tierName != "" {
				tierNames[ak] = tierName
			}
		}
	}

	for ak, tierName := range tierNames {
		pp := aggregates[ak]
		aggRep := pp.representative
		aggRep.NUMANodes = nil
		aggRep.PCIeRoots = nil
		dc := m.buildDeviceClassFromCache(pp.profile, pp.partType, aggRep, pp.cachedConfig, CouplingNone, pp.count)
		dc.Name = tierName
		dc.Labels[CoordinatorDriverName+"/tierName"] = tierName
		activeNames[dc.Name] = true
		if err := m.publishDeviceClass(ctx, dc); err != nil {
			publishErrs = append(publishErrs, fmt.Errorf("failed to publish tier DeviceClass %s: %w", dc.Name, err))
		}
	}

	// Clean up stale DeviceClasses no longer matching any partition
	activeKeys := make(map[string]bool, len(seen))
	for key, pp := range seen {
		activeKeys[key] = true
		if pp.partType == PartitionPCIeRoot && len(pp.representative.PCIeRoots) > 0 {
			sanitizedKey := truncateLabel(pp.profile) + "-" + string(pp.partType)
			if len(pp.representative.NUMANodes) > 0 {
				sanitizedKey += numaKeySuffix(pp.representative.NUMANodes)
			}
			sanitizedKey += "-" + sanitizeForName(pp.representative.PCIeRoots[0])
			if pp.cachedCoupling != CouplingNone {
				sanitizedKey += "-" + string(pp.cachedCoupling)
			}
			activeKeys[sanitizedKey] = true
		}
	}
	for ak := range aggregates {
		aggKey := truncateLabel(ak.profile) + "-" + string(ak.partType)
		activeKeys[aggKey] = true
	}
	for ak, tierName := range tierNames {
		activeKeys[truncateLabel(ak.profile)+"-"+tierName] = true
	}
	if err := m.cleanupStaleDeviceClasses(ctx, activeKeys, activeNames); err != nil {
		klog.Errorf("Failed to cleanup stale DeviceClasses: %v", err)
	}

	klog.Infof("Synced %d DeviceClasses", len(seen))
	return stdliberrors.Join(publishErrs...)
}

// computeTierName returns the human-readable tier name (eighth, quarter, half, etc.)
// for a given aggregate partition type, or "" if no well-known name applies.
func computeTierName(partType PartitionType, pp *profilePartition, allPartitions []PartitionDevice, profile string, pcieRootCount int) string {
	var rootsInPartition int
	switch partType {
	case PartitionPCIeRoot:
		rootsInPartition = 1
	case PartitionNUMA:
		rootsInPartition = countPCIeRootsInNUMA(allPartitions, profile, pp.representative.NUMANodes)
		if rootsInPartition == 0 {
			rootsInPartition = pcieRootCount / pp.count
		}
	default:
		return ""
	}
	tierName := fractionToTierName(rootsInPartition, pcieRootCount)
	if tierName == "" || tierName == "full" || tierName == string(partType) {
		return ""
	}
	return tierName
}

// isDriverReachableToAll checks if a driver's devices are reachable to all
// partition NUMA nodes via SLIT-distance NUMANodes lists. A device is reachable
// to a partition if the partition's NUMA node appears in the device's NUMANodes
// list (indicating equidistant access, e.g., same socket).
func isDriverReachableToAll(driver string, partitionNUMAs []int64, devices []TopologyDevice) bool {
	if len(partitionNUMAs) == 0 {
		return false
	}
	for _, partNUMA := range partitionNUMAs {
		reachable := false
		for _, dev := range devices {
			if baseDriverName(dev.DriverName) != driver {
				continue
			}
			for _, devNUMA := range dev.NUMANodes {
				if devNUMA == partNUMA {
					reachable = true
					break
				}
			}
			if reachable {
				break
			}
		}
		if !reachable {
			return false
		}
	}
	return true
}

// countSharingNUMAs returns how many partition NUMA nodes share access to a
// driver's devices via SLIT. This is the average NUMANodes list length across
// the driver's devices, used to divide device counts proportionally.
func countSharingNUMAs(driver string, partitionNUMAs []int64, devices []TopologyDevice) int {
	partSet := make(map[int64]bool, len(partitionNUMAs))
	for _, n := range partitionNUMAs {
		partSet[n] = true
	}
	maxSharing := 0
	for _, dev := range devices {
		if baseDriverName(dev.DriverName) != driver {
			continue
		}
		sharing := 0
		for _, n := range dev.NUMANodes {
			if partSet[n] {
				sharing++
			}
		}
		if sharing > maxSharing {
			maxSharing = sharing
		}
	}
	return maxSharing
}

// countPCIeRootsInNUMA counts how many PCIe root partitions share NUMA nodes
// with the given NUMA node set. Used to determine what fraction of the node
// a NUMA partition represents.
func countPCIeRootsInNUMA(partitions []PartitionDevice, profile string, numaNodes []int64) int {
	if len(numaNodes) == 0 {
		return 0
	}
	numaSet := make(map[int64]bool, len(numaNodes))
	for _, n := range numaNodes {
		numaSet[n] = true
	}
	count := 0
	for _, p := range partitions {
		if p.Profile != profile || p.Type != PartitionPCIeRoot {
			continue
		}
		for _, n := range p.NUMANodes {
			if numaSet[n] {
				count++
				break
			}
		}
	}
	return count
}

// cleanupStaleDeviceClasses removes DeviceClasses that no longer match any partition.
func (m *DeviceClassManager) cleanupStaleDeviceClasses(ctx context.Context, activeKeys, activeNames map[string]bool) error {
	labelSelector := fmt.Sprintf("%s/managed=true,%s/partitionType", CoordinatorDriverName, CoordinatorDriverName)
	classes, err := m.client.ResourceV1().DeviceClasses().List(ctx, metav1.ListOptions{
		LabelSelector: labelSelector,
	})
	if err != nil {
		return fmt.Errorf("failed to list DeviceClasses: %w", err)
	}

	for _, dc := range classes.Items {
		if activeNames[dc.Name] {
			continue
		}
		profile := dc.Labels[CoordinatorDriverName+"/profile"]
		partType := dc.Labels[CoordinatorDriverName+"/partitionType"]
		tierName := dc.Labels[CoordinatorDriverName+"/tierName"]
		numa := dc.Labels[CoordinatorDriverName+"/numa"]
		coupling := dc.Labels[CoordinatorDriverName+"/coupling"]

		// Tier-named aggregates use profile-tierName as their key;
		// regular partitions use profile-partitionType[-numa][-coupling].
		var key string
		if tierName != "" {
			key = profile + "-" + tierName
		} else {
			key = profile + "-" + partType
			if numa != "" {
				key += "-" + numa
			}
			if coupling != "" {
				key += "-" + coupling
			}
		}
		if _, exists := activeKeys[key]; !exists {
			if err := m.client.ResourceV1().DeviceClasses().Delete(ctx, dc.Name, metav1.DeleteOptions{}); err != nil {
				if !errors.IsNotFound(err) {
					klog.Errorf("Failed to delete stale DeviceClass %s: %v", dc.Name, err)
				}
			} else {
				klog.Infof("Deleted stale DeviceClass %s", dc.Name)
			}
		}
	}
	return nil
}

// buildDeviceClassFromCache constructs a DeviceClass using pre-computed config and coupling.
func (m *DeviceClassManager) buildDeviceClassFromCache(profile string, partType PartitionType, representative PartitionDevice, config PartitionConfig, coupling CouplingLevel, count int) *resourcev1.DeviceClass {
	nameSuffix := ""
	if len(representative.NUMANodes) > 0 && partType != PartitionFull {
		nameSuffix = numaKeySuffix(representative.NUMANodes)
	}
	if partType == PartitionPCIeRoot && len(representative.PCIeRoots) > 0 {
		nameSuffix += "-" + sanitizeForName(representative.PCIeRoots[0])
	}

	name := m.deviceClassName(profile, partType) + nameSuffix
	if coupling != CouplingNone {
		name += "-" + string(coupling)
	}

	// Build the CEL selector
	celExpr := fmt.Sprintf(
		`device.driver == %q && device.attributes[%q].partitionType == %q`,
		m.driverName, m.driverName, string(partType),
	)
	configJSON, err := json.Marshal(config)
	if err != nil {
		klog.Errorf("Failed to marshal partition config: %v", err)
		configJSON = []byte("{}")
	}

	labels := map[string]string{
		CoordinatorDriverName + "/managed":       "true",
		CoordinatorDriverName + "/profile":       truncateLabel(profile),
		CoordinatorDriverName + "/partitionType": string(partType),
	}
	if nameSuffix != "" {
		labels[CoordinatorDriverName+"/numa"] = strings.TrimPrefix(nameSuffix, "-")
	}
	if coupling != CouplingNone {
		labels[CoordinatorDriverName+"/coupling"] = string(coupling)
	}
	if count > 1 {
		labels[CoordinatorDriverName+"/count"] = fmt.Sprintf("%d", count)
	}

	return &resourcev1.DeviceClass{
		ObjectMeta: metav1.ObjectMeta{
			Name:   name,
			Labels: labels,
		},
		Spec: resourcev1.DeviceClassSpec{
			Selectors: []resourcev1.DeviceSelector{
				{
					CEL: &resourcev1.CELDeviceSelector{
						Expression: celExpr,
					},
				},
			},
			Config: []resourcev1.DeviceClassConfiguration{
				{
					DeviceConfiguration: resourcev1.DeviceConfiguration{
						Opaque: &resourcev1.OpaqueDeviceConfiguration{
							Driver:     m.driverName,
							Parameters: runtime.RawExtension{Raw: configJSON},
						},
					},
				},
			},
		},
	}
}

// buildPartitionConfig builds the opaque PartitionConfig from the representative partition.
func (m *DeviceClassManager) buildPartitionConfig(_ PartitionType, representative PartitionDevice) (PartitionConfig, CouplingLevel) {
	config := PartitionConfig{
		Kind: "PartitionConfig",
		Mode: OfferingModeContainer,
	}

	// Sub-resources: one entry per driver with its device count, optional capacity,
	// per-driver CEL selectors for NUMA pinning, and partition mode if applicable.
	for driver, count := range representative.DeviceCounts {
		sr := SubResourceConfig{
			SourceDriver: driver,
			DeviceClass:  m.rules.GetDeviceClassForDriver(driver),
			Count:        count,
		}
		if representative.DeviceCapacity != nil {
			if cap, ok := representative.DeviceCapacity[driver]; ok {
				sr.Capacity = cap
			}
		}

		// Detect partition mode from representative devices' extended attributes.
		// Drivers advertise mode via attributes like "gpu.amd.com/partitionMode".
		for _, dev := range representative.Devices {
			if baseDriverName(dev.DriverName) != driver {
				continue
			}
			if modeAttr, mode := detectPartitionModeAttr(dev); mode != "" {
				sr.PartitionMode = mode
				parts := strings.SplitN(modeAttr, "/", 2)
				if len(parts) == 2 {
					sr.Selectors = append(sr.Selectors,
						fmt.Sprintf(`device.attributes[%q].%s == %q`, parts[0], parts[1], mode))
				} else {
					// Unqualified attribute — qualify with driver name.
					sr.Selectors = append(sr.Selectors,
						fmt.Sprintf(`device.attributes[%q].%s == %q`, driver, modeAttr, mode))
				}
				break
			}
		}

		// Generate per-driver NUMA CEL selector from topology rules.
		// Each driver publishes NUMA under its own attribute namespace
		// (e.g., gpu.amd.com/numaNode, dra.cpu/numaNodeID). The topology
		// rules tell us which attribute name each driver uses.
		if len(representative.NUMANodes) > 0 {
			if attr, ok := m.rules.GetNUMAAttributeForDriver(driver); ok {
				// Qualify unqualified attributes with the driver name.
				// E.g., "numaNode" for driver "gpu.amd.com" → "gpu.amd.com/numaNode"
				// so the CEL expression uses device.attributes["gpu.amd.com"].numaNode
				if !strings.Contains(attr, "/") {
					attr = driver + "/" + attr
				}
				cel := BuildNUMACELSelector(attr, representative.NUMANodes)
				if cel != "" {
					sr.Selectors = append(sr.Selectors, cel)
				}
			} else {
				// Fallback: driver publishes the standard resource.kubernetes.io/numaNode directly
				cel := BuildNUMACELSelector(AttrNUMANode, representative.NUMANodes)
				if cel != "" {
					sr.Selectors = append(sr.Selectors, cel)
				}
			}
		}

		config.SubResources = append(config.SubResources, sr)
	}

	// No cross-driver matchAttribute for NUMA — each sub-resource has its own
	// per-driver CEL selector derived from topology rules. This eliminates the
	// requirement for all drivers to publish NUMA under a common attribute name.

	// Match constraint alignments from topology rules with distance-based fallback.
	// For rules with FallbackAttribute, check if the primary constraint is satisfiable
	// for this partition's devices. If yes, emit it (tight coupling). If not, skip it
	// and rely on the per-driver NUMA CEL selectors already generated above (loose coupling).
	coupling := CouplingNone
	matchRules := m.rules.GetMatchConstraintRules()
	for _, rule := range matchRules {
		if rule.Driver != "" {
			if _, ok := representative.DeviceCounts[rule.Driver]; !ok {
				continue
			}
		}

		enforcement := rule.Enforcement
		if enforcement == "" {
			enforcement = EnforcementRequired
		}

		// Build request names for this constraint: only include drivers whose
		// devices publish the attribute as a scalar value. Drivers that only
		// publish list-type attributes (e.g., CPU's pcieRoot list) are excluded
		// because the scheduler's matchAttribute uses scalar equality, not list
		// membership. List-type attributes are handled by CEL includes() selectors.
		var constraintRequests []string
		if len(representative.Devices) > 0 {
			driversWithScalarAttribute := make(map[string]bool)
			for _, dev := range representative.Devices {
				if deviceHasScalarAttribute(dev, rule.Attribute) {
					driversWithScalarAttribute[baseDriverName(dev.DriverName)] = true
				}
			}
			for driver := range representative.DeviceCounts {
				if driversWithScalarAttribute[baseDriverName(driver)] {
					constraintRequests = append(constraintRequests, m.rules.GetDeviceClassForDriver(driver))
				}
			}
			if len(constraintRequests) == 0 {
				continue
			}
		} else {
			// No device data available — include all drivers
			for driver := range representative.DeviceCounts {
				constraintRequests = append(constraintRequests, m.rules.GetDeviceClassForDriver(driver))
			}
		}

		if rule.FallbackAttribute != "" {
			// Distance-based fallback: check if primary constraint is satisfiable
			// for this specific partition's devices.
			if isPartitionConstraintSatisfiable(representative.Devices, rule.Attribute, representative.DeviceCounts) {
				// Primary (tight) constraint works for this partition
				config.Alignments = append(config.Alignments, AlignmentConfig{
					Attribute:   rule.Attribute,
					Requests:    constraintRequests,
					Enforcement: enforcement,
				})
				// Upgrade coupling to tight (never downgrade from tight)
				coupling = CouplingTight
				klog.V(2).Infof("Partition %s: primary constraint %s satisfiable (tight coupling)",
					representative.Name, rule.Attribute)
			} else {
				// Primary unsatisfiable — fall back to looser alignment.
				// Per-driver NUMA CEL selectors are already in place, so we
				// just don't add the primary matchAttribute constraint.
				if coupling != CouplingTight {
					coupling = CouplingLoose
				}
				klog.V(2).Infof("Partition %s: primary constraint %s unsatisfiable, falling back to %s (loose coupling)",
					representative.Name, rule.Attribute, rule.FallbackAttribute)
			}
		} else {
			// No fallback: emit as before
			config.Alignments = append(config.Alignments, AlignmentConfig{
				Attribute:   rule.Attribute,
				Requests:    constraintRequests,
				Enforcement: enforcement,
			})
		}
	}

	sortPartitionConfig(&config)
	return config, coupling
}

// buildPartitionAggregateConfig builds a PartitionConfig without NUMA/PCIe
// selectors for aggregate DeviceClasses. Keeps alignment constraints and
// device counts but lets the scheduler choose placement freely.
func (m *DeviceClassManager) buildPartitionAggregateConfig(representative PartitionDevice) (PartitionConfig, CouplingLevel) {
	config := PartitionConfig{
		Kind: "PartitionConfig",
		Mode: OfferingModeContainer,
	}

	for driver, count := range representative.DeviceCounts {
		sr := SubResourceConfig{
			SourceDriver: driver,
			DeviceClass:  m.rules.GetDeviceClassForDriver(driver),
			Count:        count,
		}
		if representative.DeviceCapacity != nil {
			if cap, ok := representative.DeviceCapacity[driver]; ok {
				sr.Capacity = cap
			}
		}
		config.SubResources = append(config.SubResources, sr)
	}

	coupling := CouplingNone
	matchRules := m.rules.GetMatchConstraintRules()
	for _, rule := range matchRules {
		if rule.Driver != "" {
			if _, ok := representative.DeviceCounts[rule.Driver]; !ok {
				continue
			}
		}

		// For aggregate DeviceClasses, include all drivers that publish the
		// constraint attribute in any form (scalar or list). List-type attributes
		// work with matchAttribute constraints via intersection — e.g., a NIC VF
		// with numaNode=[0,1,2,3] will match any device on NUMA 0, 1, 2, or 3.
		// Try the primary attribute first; fall back if not enough drivers match.
		constraintAttr := rule.Attribute
		var constraintRequests []string
		if len(representative.Devices) > 0 {
			driversWithAttribute := make(map[string]bool)
			for _, dev := range representative.Devices {
				if deviceHasAttribute(dev, constraintAttr) {
					driversWithAttribute[baseDriverName(dev.DriverName)] = true
				}
			}
			for driver := range representative.DeviceCounts {
				if driversWithAttribute[baseDriverName(driver)] {
					constraintRequests = append(constraintRequests, m.rules.GetDeviceClassForDriver(driver))
				}
			}
			// Fall back to the fallback attribute if primary doesn't cover enough drivers
			if len(constraintRequests) < 2 && rule.FallbackAttribute != "" {
				constraintAttr = rule.FallbackAttribute
				driversWithAttribute = make(map[string]bool)
				for _, dev := range representative.Devices {
					if deviceHasAttribute(dev, constraintAttr) {
						driversWithAttribute[baseDriverName(dev.DriverName)] = true
					}
				}
				constraintRequests = nil
				for driver := range representative.DeviceCounts {
					if driversWithAttribute[baseDriverName(driver)] {
						constraintRequests = append(constraintRequests, m.rules.GetDeviceClassForDriver(driver))
					}
				}
			}
			if len(constraintRequests) == 0 {
				continue
			}
		}

		if len(constraintRequests) < 2 {
			continue
		}

		enforcement := rule.Enforcement
		if enforcement == "" {
			enforcement = EnforcementRequired
		}

		config.Alignments = append(config.Alignments, AlignmentConfig{
			Attribute:   constraintAttr,
			Requests:    constraintRequests,
			Enforcement: enforcement,
		})
		coupling = CouplingTight

		// If the primary constraint didn't cover all drivers and a fallback
		// attribute exists, add a second alignment on the fallback attribute
		// covering all drivers. This ensures devices like memory (which lack
		// pcieRoot but have numaNode) are co-located with the rest.
		if rule.FallbackAttribute != "" && constraintAttr != rule.FallbackAttribute {
			coveredClasses := make(map[string]bool)
			for _, r := range constraintRequests {
				coveredClasses[r] = true
			}
			uncoveredCount := 0
			for driver := range representative.DeviceCounts {
				if !coveredClasses[m.rules.GetDeviceClassForDriver(driver)] {
					uncoveredCount++
				}
			}
			if uncoveredCount > 0 {
				fallbackDrivers := make(map[string]bool)
				for _, dev := range representative.Devices {
					if deviceHasAttribute(dev, rule.FallbackAttribute) {
						fallbackDrivers[baseDriverName(dev.DriverName)] = true
					}
				}
				var fallbackRequests []string
				for driver := range representative.DeviceCounts {
					if fallbackDrivers[baseDriverName(driver)] {
						fallbackRequests = append(fallbackRequests, m.rules.GetDeviceClassForDriver(driver))
					}
				}
				if len(fallbackRequests) > len(constraintRequests) {
					config.Alignments = append(config.Alignments, AlignmentConfig{
						Attribute:   rule.FallbackAttribute,
						Requests:    fallbackRequests,
						Enforcement: enforcement,
					})
				}
			}
		}
	}

	sortPartitionConfig(&config)
	return config, coupling
}

// deviceClassName generates a deterministic DeviceClass name.
func (m *DeviceClassManager) deviceClassName(profile string, partType PartitionType) string {
	// Sanitize profile for DNS label compatibility
	sanitized := strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
			return r
		}
		if r >= 'A' && r <= 'Z' {
			return r + ('a' - 'A')
		}
		return '-'
	}, profile)

	// Trim leading/trailing dashes and collapse consecutive dashes
	for strings.Contains(sanitized, "--") {
		sanitized = strings.ReplaceAll(sanitized, "--", "-")
	}
	sanitized = strings.Trim(sanitized, "-")

	if sanitized == "" {
		sanitized = "default"
	}

	// Truncate profile to fit within DNS label limits (63 chars max)
	// Keep partition type suffix intact for uniqueness
	suffix := "-" + string(partType)
	maxProfileLen := 63 - len(suffix)
	if len(sanitized) > maxProfileLen {
		h := sha256.Sum256([]byte(sanitized))
		hash := hex.EncodeToString(h[:4])
		sanitized = sanitized[:maxProfileLen-9] + "-" + hash
	}

	return sanitized + suffix
}

// truncateLabel truncates a string to fit K8s label value limits (63 chars max).
// If truncation is needed, appends a short hash to preserve uniqueness.
func truncateLabel(s string) string {
	if len(s) <= 63 {
		return s
	}
	h := sha256.Sum256([]byte(s))
	hash := hex.EncodeToString(h[:4]) // 8 hex chars
	return s[:54] + "-" + hash
}

// numaKeySuffix returns a DNS-safe suffix encoding the NUMA node IDs.
// e.g., [0] → "-numa0", [0, 1] → "-numa0-1"
func numaKeySuffix(numaNodes []int64) string {
	if len(numaNodes) == 0 {
		return ""
	}
	s := fmt.Sprintf("-numa%d", numaNodes[0])
	for _, n := range numaNodes[1:] {
		s += fmt.Sprintf("-%d", n)
	}
	return s
}

// isPartitionConstraintSatisfiable checks whether a partition's devices can
// satisfy a matchAttribute constraint. It groups the partition's devices by
// the attribute value and checks if any group meets all driver count requirements.
// This is a local check on the partition's Devices slice, not a cluster-wide check.
func isPartitionConstraintSatisfiable(devices []TopologyDevice, attribute string, driverCounts map[string]int) bool {
	groups := make(map[string]map[string]int) // attrValue → baseDriverName → count

	// Track which drivers actually publish this attribute
	driversWithAttribute := make(map[string]bool)

	for _, dev := range devices {
		vals := deviceAttributeValues(dev, attribute)
		if len(vals) == 0 {
			continue // Device doesn't publish this attribute
		}
		driver := baseDriverName(dev.DriverName)
		driversWithAttribute[driver] = true
		for _, val := range vals {
			if groups[val] == nil {
				groups[val] = make(map[string]int)
			}
			groups[val][driver]++
		}
	}

	// Need at least 2 drivers with the attribute for a meaningful constraint
	if len(driversWithAttribute) < 2 {
		return false
	}

	for _, driverMap := range groups {
		satisfied := true
		for driver, needed := range driverCounts {
			base := baseDriverName(driver)
			// Only check drivers that actually publish this attribute.
			// CPU/memory don't publish pcieRoot — skip them.
			if !driversWithAttribute[base] {
				continue
			}
			if driverMap[base] < needed {
				satisfied = false
				break
			}
		}
		if satisfied {
			return true
		}
	}
	return false
}

// SyncGroupingDeviceClasses creates or updates DeviceClass objects for each
// satisfiable grouping instance discovered across all nodes.
func (m *DeviceClassManager) SyncGroupingDeviceClasses(ctx context.Context, results []GroupingResult) error {
	type groupingEntry struct {
		representative GroupingInstance
		config         PartitionConfig
		count          int
	}

	// A grouping whose instances disagree on the request contract (e.g. two
	// ConfigMaps sharing a name) is skipped; it must not block other groupings.
	var publishErrs []error
	conflicted := make(map[string]struct{})
	contracts := make(map[string]string)
	seen := make(map[string]*groupingEntry)
	for _, result := range results {
		for _, inst := range result.Instances {
			config := m.buildGroupingConfig(inst)
			key := groupingInstanceKey(inst)

			contract := groupingRequestContractKey(inst)
			if prev, ok := contracts[inst.GroupingName]; !ok {
				contracts[inst.GroupingName] = contract
			} else if prev != contract {
				if _, dup := conflicted[inst.GroupingName]; !dup {
					conflicted[inst.GroupingName] = struct{}{}
					publishErrs = append(publishErrs, fmt.Errorf("grouping %q has conflicting explicit request contract", inst.GroupingName))
				}
				continue
			}

			if entry, ok := seen[key]; ok {
				entry.count++
			} else {
				seen[key] = &groupingEntry{
					representative: inst,
					config:         config,
					count:          1,
				}
			}
		}
	}

	for key, entry := range seen {
		if _, bad := conflicted[entry.representative.GroupingName]; bad {
			delete(seen, key)
		}
	}

	// Non-rail instance names changed from the historical -railN form to
	// topology-specific names. Refuse an in-place upgrade while an old class
	// remains, so claims keep their old target until the operator removes the
	// legacy classes and explicitly crosses the migration boundary.
	nonRailGroupings := make(map[string]struct{})
	for _, entry := range seen {
		if !entry.representative.Rail {
			nonRailGroupings[entry.representative.GroupingName] = struct{}{}
		}
	}
	if len(nonRailGroupings) > 0 {
		classes, err := m.client.ResourceV1().DeviceClasses().List(ctx, metav1.ListOptions{
			LabelSelector: fmt.Sprintf("%s/managed=true,%s/grouping", CoordinatorDriverName, CoordinatorDriverName),
		})
		if err != nil {
			return fmt.Errorf("failed to check legacy grouping DeviceClasses: %w", err)
		}
		for _, dc := range classes.Items {
			if _, ok := nonRailGroupings[dc.Labels[CoordinatorDriverName+"/grouping"]]; !ok {
				continue
			}
			prefix := sanitizeForName(dc.Labels[CoordinatorDriverName+"/grouping"]) + "-rail"
			if dc.Labels[CoordinatorDriverName+"/railIndex"] != "" && strings.HasPrefix(dc.Name, prefix) {
				return fmt.Errorf("legacy non-rail grouping DeviceClass %q requires migration; remove it before publishing topology-specific names", dc.Name)
			}
		}
	}

	// Emit per-instance DeviceClasses. Errors are
	// accumulated rather than returned immediately so that one unpublishable
	// grouping does not block every other grouping from reconciling.
	for key, entry := range seen {
		dc := m.buildGroupingDeviceClass(key, entry.representative, entry.config, entry.count)
		dc.Name = groupingDeviceClassName(entry.representative)
		if err := m.publishDeviceClass(ctx, dc); err != nil {
			publishErrs = append(publishErrs, fmt.Errorf("failed to publish DeviceClass %s: %w", dc.Name, err))
		}
	}

	// Emit aggregate DeviceClasses (one per grouping name, no NUMA selector).
	// Lets users request "any gpu-nic-pair" without specifying a NUMA node;
	// the scheduler finds a satisfiable placement automatically.
	//
	// All instances for a grouping name share one merged source, so intent is
	// identical; combining sources under one name later would invalidate this.
	//
	// Use intersection of device counts, mirroring the partition-aggregate
	// path above: only include drivers present on ALL instances of this
	// grouping name, so the aggregate is schedulable (and truthfully
	// describable) regardless of which rail/node it resolves to. A grouping
	// can be asymmetric across rails (e.g. a GPU+NIC pair present on rail 0
	// but only a bare GPU on rail 1); publishing one arbitrary instance's
	// config as "the" aggregate would misrepresent rails that don't have it.
	type groupingAggregateState struct {
		groupingName     string
		alignment        string
		mode             OfferingMode
		requests         map[string]RequestContract
		contractKey      string
		intent           IntentMetadata // identical across instances, per the note above
		acc              *deviceIntersectionState
		minInstanceIndex int
		count            int // sum of entry.count
	}
	aggStates := make(map[string]*groupingAggregateState)
	for _, entry := range seen {
		name := entry.representative.GroupingName
		state, ok := aggStates[name]
		if !ok {
			state = &groupingAggregateState{
				groupingName:     name,
				alignment:        entry.representative.Alignment,
				mode:             entry.representative.Mode,
				requests:         entry.representative.Requests,
				contractKey:      groupingRequestContractKey(entry.representative),
				intent:           entry.representative.Intent,
				acc:              newDeviceIntersectionState(),
				minInstanceIndex: entry.representative.InstanceIndex,
			}
			aggStates[name] = state
		} else if state.contractKey != groupingRequestContractKey(entry.representative) {
			// Unreachable while the first pass drops conflicting groupings.
			publishErrs = append(publishErrs, fmt.Errorf("grouping %q has conflicting explicit request contract", name))
			continue
		}
		state.count += entry.count
		if entry.representative.InstanceIndex < state.minInstanceIndex {
			state.minInstanceIndex = entry.representative.InstanceIndex
		}
		state.acc.add(entry.representative.DeviceCounts, entry.representative.DeviceCapacity, entry.representative.Devices)
	}
	aggregates := make(map[string]*groupingEntry)
	for name, state := range aggStates {
		intersectedCounts, intersectedCap := state.acc.intersect(nil)
		mergedRep := GroupingInstance{
			GroupingName:   state.groupingName,
			Alignment:      state.alignment,
			Mode:           state.mode,
			Requests:       state.requests,
			Intent:         state.intent,
			DeviceCounts:   intersectedCounts,
			DeviceCapacity: intersectedCap,
			Devices:        state.acc.devices,
			InstanceIndex:  state.minInstanceIndex,
		}
		aggregates[name] = &groupingEntry{
			representative: mergedRep,
			config:         m.buildGroupingAggregateConfig(mergedRep),
			count:          state.count,
		}
	}
	for _, entry := range aggregates {
		aggKey := truncateLabel(entry.representative.GroupingName) + "-" + sanitizeForName(entry.representative.Alignment)
		dc := m.buildGroupingDeviceClass(aggKey, entry.representative, entry.config, entry.count)
		dc.Name = sanitizeForName(entry.representative.GroupingName)
		delete(dc.Labels, CoordinatorDriverName+"/numa")
		delete(dc.Labels, CoordinatorDriverName+"/railIndex")
		applyIntentMetadata(dc, entry.representative.Intent)
		if err := m.publishDeviceClass(ctx, dc); err != nil {
			publishErrs = append(publishErrs, fmt.Errorf("failed to publish aggregate DeviceClass %s: %w", dc.Name, err))
		}
	}

	// activeNames includes every entry regardless of publish success/failure,
	// so a transient publish error does not cause cleanup to delete a
	// DeviceClass that a prior successful reconcile already created.
	activeNames := make(map[string]bool, len(seen)+len(aggregates))
	for _, entry := range seen {
		name := groupingDeviceClassName(entry.representative)
		activeNames[name] = true
	}
	for _, entry := range aggregates {
		name := sanitizeForName(entry.representative.GroupingName)
		activeNames[name] = true
	}
	if err := m.cleanupStaleGroupingDeviceClasses(ctx, activeNames); err != nil {
		klog.Errorf("Failed to cleanup stale grouping DeviceClasses: %v", err)
	}

	klog.Infof("Synced %d grouping DeviceClasses", len(seen))
	return stdliberrors.Join(publishErrs...)
}

func groupingInstanceKey(inst GroupingInstance) string {
	key := truncateLabel(inst.GroupingName) + "-" + sanitizeForName(inst.Alignment)
	// Only the requested alignment identifies an instance. Other topology
	// attributes may differ between devices that share the same published
	// DeviceClass and must not create duplicate entries.
	switch inst.Alignment {
	case "pcieRoot":
		if len(inst.PCIeRoots) > 0 {
			// Keep the raw topology value in the internal key. The published
			// DeviceClass name is sanitized separately, so two distinct roots
			// that normalize to the same DNS label remain distinguishable.
			key += "-" + strings.Join(inst.PCIeRoots, "-")
		} else {
			key += fmt.Sprintf("-instance%d", inst.InstanceIndex)
		}
	case "numaNode":
		if nk := numaKey(inst.NUMANodes); nk != "" {
			key += "-numa" + nk
		} else {
			key += fmt.Sprintf("-instance%d", inst.InstanceIndex)
		}
	case "socket":
		if len(inst.Sockets) > 0 {
			values := make([]string, len(inst.Sockets))
			for i, value := range inst.Sockets {
				values[i] = strconv.FormatInt(value, 10)
			}
			key += "-socket" + strings.Join(values, "-")
		} else {
			key += fmt.Sprintf("-instance%d", inst.InstanceIndex)
		}
	default:
		key += fmt.Sprintf("-instance%d", inst.InstanceIndex)
	}
	return key
}

func groupingRequestContractKey(inst GroupingInstance) string {
	mode := inst.Mode
	if mode == "" {
		mode = OfferingModeContainer
	}
	contract := struct {
		Mode     OfferingMode               `json:"mode,omitempty"`
		Requests map[string]RequestContract `json:"requests,omitempty"`
	}{Mode: mode, Requests: inst.Requests}
	data, _ := json.Marshal(contract)
	return string(data)
}

func groupingDeviceClassName(inst GroupingInstance) string {
	base := sanitizeForName(inst.GroupingName)
	if inst.Rail {
		return sanitizeDNSLabel(fmt.Sprintf("%s-rail%d", base, inst.InstanceIndex))
	}

	var suffix string
	switch inst.Alignment {
	case "numaNode":
		if len(inst.NUMANodes) > 0 {
			values := make([]string, len(inst.NUMANodes))
			for i, value := range inst.NUMANodes {
				values[i] = fmt.Sprintf("%d", value)
			}
			suffix = "numa" + strings.Join(values, "-")
		}
	case "pcieRoot":
		if len(inst.PCIeRoots) > 0 {
			suffix = "pcie-" + sanitizeForName(strings.Join(inst.PCIeRoots, "-"))
		}
	case "socket":
		if len(inst.Sockets) > 0 {
			values := make([]string, len(inst.Sockets))
			for i, value := range inst.Sockets {
				values[i] = fmt.Sprintf("%d", value)
			}
			suffix = "socket" + strings.Join(values, "-")
		}
	}
	if suffix == "" {
		suffix = fmt.Sprintf("%s%d", sanitizeForName(inst.Alignment), inst.InstanceIndex)
	}
	return sanitizeDNSLabel(base + "-" + suffix)
}

// buildGroupingConfig builds the opaque PartitionConfig from a grouping instance.
func (m *DeviceClassManager) buildGroupingConfig(inst GroupingInstance) PartitionConfig {
	return m.buildGroupingConfigInternal(inst, true)
}

// buildGroupingAggregateConfig builds a PartitionConfig without NUMA selectors,
// so the scheduler can place on any NUMA node with available devices.
func (m *DeviceClassManager) buildGroupingAggregateConfig(inst GroupingInstance) PartitionConfig {
	return m.buildGroupingConfigInternal(inst, false)
}

func (m *DeviceClassManager) buildGroupingConfigInternal(inst GroupingInstance, includeNUMA bool) PartitionConfig {
	config := PartitionConfig{
		Kind: "PartitionConfig",
		Mode: inst.Mode,
	}
	if config.Mode == "" {
		config.Mode = OfferingModeContainer
	}

	for driverClass, count := range inst.DeviceCounts {
		// Clone: the NUMA selector appended below must not write into the
		// slice shared with the DeviceGrouping.
		contract := inst.Requests[driverClass].clone()
		sr := SubResourceConfig{
			SourceDriver: m.driverForClass(driverClass),
			DeviceClass:  inst.requestClass(driverClass),
			Count:        count,
			Passthrough:  config.Mode == OfferingModePassthrough && contract.Passthrough,
			Selectors:    contract.Selectors,
			Opaque:       contract.Opaque,
		}

		if cap, ok := inst.DeviceCapacity[driverClass]; ok {
			sr.Capacity = cap
		}

		if includeNUMA && len(inst.NUMANodes) > 0 {
			// The selector is evaluated on the devices requestClass allocates,
			// so it must use that driver's attribute domain.
			driver := contract.Driver
			if driver == "" {
				driver = m.driverForClass(driverClass)
			}
			if attr, ok := m.rules.GetNUMAAttributeForDriver(driver); ok {
				if !strings.Contains(attr, "/") {
					attr = driver + "/" + attr
				}
				cel := BuildNUMACELSelector(attr, inst.NUMANodes)
				if cel != "" {
					sr.Selectors = append(sr.Selectors, cel)
				}
			} else {
				cel := BuildNUMACELSelector(AttrNUMANode, inst.NUMANodes)
				if cel != "" {
					sr.Selectors = append(sr.Selectors, cel)
				}
			}
		}

		config.SubResources = append(config.SubResources, sr)
	}

	matchRules := m.rules.GetMatchConstraintRules()
	for _, rule := range matchRules {
		if rule.Driver != "" {
			if _, ok := inst.DeviceCounts[m.rules.GetDeviceClassForDriver(rule.Driver)]; !ok {
				continue
			}
		}

		var constraintRequests []string
		if len(inst.Devices) > 0 {
			driversWithAttribute := make(map[string]bool)
			for _, dev := range inst.Devices {
				val := deviceAttributeValueString(dev, rule.Attribute)
				if val != "" {
					driversWithAttribute[baseDriverName(dev.DriverName)] = true
				}
			}
			for driver := range inst.DeviceCounts {
				rawDriver := m.driverForClass(driver)
				if driversWithAttribute[baseDriverName(rawDriver)] {
					if !requestDriverPublishes(inst.Requests[driver].Driver, rawDriver, rule.Attribute) {
						klog.V(2).Infof("Grouping %q: skipping %s in %s alignment; request driver %q may not publish it",
							inst.GroupingName, inst.requestClass(driver), rule.Attribute, inst.Requests[driver].Driver)
						continue
					}
					requestClass := inst.requestClass(driver)
					constraintRequests = append(constraintRequests, requestClass)
				}
			}
		}

		if len(constraintRequests) < 2 {
			continue
		}

		enforcement := rule.Enforcement
		if enforcement == "" {
			enforcement = EnforcementRequired
		}

		config.Alignments = append(config.Alignments, AlignmentConfig{
			Attribute:   rule.Attribute,
			Requests:    constraintRequests,
			Enforcement: enforcement,
		})
	}

	sortPartitionConfig(&config)
	return config
}

// buildGroupingDeviceClass constructs a DeviceClass for a grouping instance.
func (m *DeviceClassManager) buildGroupingDeviceClass(
	key string,
	representative GroupingInstance,
	config PartitionConfig,
	count int,
) *resourcev1.DeviceClass {
	name := sanitizeDNSLabel(key)

	celExpr := fmt.Sprintf(
		`device.driver == %q && device.attributes[%q].grouping == %q`,
		m.driverName, m.driverName, representative.GroupingName,
	)

	configJSON, err := json.Marshal(config)
	if err != nil {
		klog.Errorf("Failed to marshal grouping config: %v", err)
		configJSON = []byte("{}")
	}

	labels := map[string]string{
		CoordinatorDriverName + "/managed":   "true",
		CoordinatorDriverName + "/grouping":  truncateLabel(representative.GroupingName),
		CoordinatorDriverName + "/alignment": representative.Alignment,
	}
	if representative.Rail {
		labels[CoordinatorDriverName+"/railIndex"] = fmt.Sprintf("%d", representative.InstanceIndex)
	}
	if len(representative.NUMANodes) > 0 {
		labels[CoordinatorDriverName+"/numa"] = numaKey(representative.NUMANodes)
	}
	if count > 1 {
		labels[CoordinatorDriverName+"/count"] = fmt.Sprintf("%d", count)
	}

	return &resourcev1.DeviceClass{
		ObjectMeta: metav1.ObjectMeta{
			Name:   name,
			Labels: labels,
		},
		Spec: resourcev1.DeviceClassSpec{
			Selectors: []resourcev1.DeviceSelector{
				{
					CEL: &resourcev1.CELDeviceSelector{
						Expression: celExpr,
					},
				},
			},
			Config: []resourcev1.DeviceClassConfiguration{
				{
					DeviceConfiguration: resourcev1.DeviceConfiguration{
						Opaque: &resourcev1.OpaqueDeviceConfiguration{
							Driver:     m.driverName,
							Parameters: runtime.RawExtension{Raw: configJSON},
						},
					},
				},
			},
		},
	}
}

func applyIntentMetadata(dc *resourcev1.DeviceClass, intent IntentMetadata) {
	if !intent.IsOffering() {
		return
	}

	if intent.IntentLevel != "" || intent.Visibility != "" {
		if dc.Labels == nil {
			dc.Labels = make(map[string]string)
		}
		if intent.IntentLevel != "" {
			dc.Labels[CoordinatorDriverName+"/intent-level"] = intent.IntentLevel
		}
		if intent.Visibility != "" {
			dc.Labels[CoordinatorDriverName+"/visibility"] = intent.Visibility
		}
	}

	if intent.DisplayName != "" || intent.Description != "" || len(intent.Categories) > 0 || len(intent.WorkloadTypes) > 0 {
		if dc.Annotations == nil {
			dc.Annotations = make(map[string]string)
		}
		if intent.DisplayName != "" {
			dc.Annotations[CoordinatorDriverName+"/display-name"] = intent.DisplayName
		}
		if intent.Description != "" {
			dc.Annotations[CoordinatorDriverName+"/description"] = intent.Description
		}
		if len(intent.Categories) > 0 {
			dc.Annotations[CoordinatorDriverName+"/categories"] = strings.Join(intent.Categories, ",")
		}
		if len(intent.WorkloadTypes) > 0 {
			dc.Annotations[CoordinatorDriverName+"/workload-types"] = strings.Join(intent.WorkloadTypes, ",")
		}
	}
}

// cleanupStaleGroupingDeviceClasses removes grouping DeviceClasses that no longer match.
func (m *DeviceClassManager) cleanupStaleGroupingDeviceClasses(ctx context.Context, active map[string]bool) error {
	labelSelector := fmt.Sprintf("%s/managed=true,%s/grouping", CoordinatorDriverName, CoordinatorDriverName)
	classes, err := m.client.ResourceV1().DeviceClasses().List(ctx, metav1.ListOptions{
		LabelSelector: labelSelector,
	})
	if err != nil {
		return fmt.Errorf("failed to list grouping DeviceClasses: %w", err)
	}

	for _, dc := range classes.Items {
		if _, exists := active[dc.Name]; !exists {
			if err := m.client.ResourceV1().DeviceClasses().Delete(ctx, dc.Name, metav1.DeleteOptions{}); err != nil {
				if !errors.IsNotFound(err) {
					klog.Errorf("Failed to delete stale grouping DeviceClass %s: %v", dc.Name, err)
				}
			} else {
				klog.Infof("Deleted stale grouping DeviceClass %s", dc.Name)
			}
		}
	}
	return nil
}

// requestDriverPublishes reports whether a request served by requestDriver can
// be expected to publish attribute. matchAttribute fails when any allocated
// device lacks the attribute, so a driver-specific attribute is only used when
// the request driver owns that domain; standard resource.kubernetes.io
// attributes describe the physical device and carry over.
func requestDriverPublishes(requestDriver, sourceDriver, attribute string) bool {
	if requestDriver == "" || baseDriverName(requestDriver) == baseDriverName(sourceDriver) {
		return true
	}
	domain, _, _ := strings.Cut(attribute, "/")
	return domain == "resource.kubernetes.io" || baseDriverName(domain) == baseDriverName(requestDriver)
}

// driverForClass returns the raw driver name for a DeviceClass name.
// If a topology rule overrides the class name, this reverse-maps it.
func (m *DeviceClassManager) driverForClass(className string) string {
	for _, rule := range m.rules.GetRules() {
		if rule.DeviceClass == className {
			return rule.Driver
		}
	}
	return className
}

// sanitizeDNSLabel converts a string to a valid DNS label (max 63 chars).
func sanitizeDNSLabel(s string) string {
	sanitized := strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
			return r
		}
		if r >= 'A' && r <= 'Z' {
			return r + ('a' - 'A')
		}
		return '-'
	}, s)

	for strings.Contains(sanitized, "--") {
		sanitized = strings.ReplaceAll(sanitized, "--", "-")
	}
	sanitized = strings.Trim(sanitized, "-")

	if sanitized == "" {
		sanitized = "default"
	}

	if len(sanitized) > 63 {
		h := sha256.Sum256([]byte(sanitized))
		hash := hex.EncodeToString(h[:4])
		sanitized = sanitized[:54] + "-" + hash
	}

	return sanitized
}

type frac struct{ n, d int }

var fractionNames = map[frac]string{
	{1, 16}: "sixteenth",
	{1, 12}: "twelfth",
	{1, 8}:  "eighth",
	{1, 6}:  "sixth",
	{1, 4}:  "quarter",
	{1, 3}:  "third",
	{1, 2}:  "half",
	{1, 1}:  "full",
}

// fractionToTierName maps a reduced fraction (numerator/denominator) to a
// human-readable tier name. Returns "" for fractions without a well-known name.
func fractionToTierName(numerator, denominator int) string {
	if denominator == 0 || numerator == 0 {
		return ""
	}
	g := gcd(numerator, denominator)
	return fractionNames[frac{numerator / g, denominator / g}]
}

func gcd(a, b int) int {
	for b != 0 {
		a, b = b, a%b
	}
	return a
}

// partitionModeAttributeSuffixes lists attribute name suffixes that indicate
// a device's partition mode (e.g., "partitionMode", "computePartition").
var partitionModeAttributeSuffixes = []string{
	"partitionMode",
	"computePartition",
	"mode",
}

// detectPartitionModeAttr returns the attribute name and mode value from a
// device's extended attributes. Returns ("", "") if no partition mode found.
func detectPartitionModeAttr(dev TopologyDevice) (attrName string, mode string) {
	for name, val := range dev.ExtendedAttributes {
		for _, suffix := range partitionModeAttributeSuffixes {
			if strings.HasSuffix(name, "/"+suffix) || name == suffix {
				if val.StringValue != nil {
					return name, *val.StringValue
				}
			}
		}
	}
	return "", ""
}

// tcOwnedLabelPrefix is the key prefix publishDeviceClass uses to decide
// which labels/annotations it owns on a DeviceClass. Always derived from the
// CoordinatorDriverName const (not m.driverName, which is configurable and
// only appears in CEL expressions and Opaque.Driver, never in a metadata key).
const tcOwnedLabelPrefix = CoordinatorDriverName + "/"

// stringMapEqual compares two string maps by content, treating nil and empty
// maps as equal (unlike reflect/apiequality.Semantic.DeepEqual, which treats
// them as different). Without this, a foreign actor setting an empty
// labels/annotations map (e.g. `{}`) would make publishDeviceClass see a
// perpetual diff against mergeTCOwnedMetadata's nil-when-empty result.
func stringMapEqual(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if bv, ok := b[k]; !ok || bv != v {
			return false
		}
	}
	return true
}

// mergeTCOwnedMetadata returns a copy of existing merged with built's
// TC-owned keys: every TC-owned key present on built is set (added or
// overwritten), and every TC-owned key present on existing but absent from
// built is deleted. Keys not owned by TC (no nodepartition.dra.k8s.io/
// prefix) are left untouched, so labels/annotations set by kubectl, Helm,
// ArgoCD, etc. survive reconciliation.
func mergeTCOwnedMetadata(existing, built map[string]string) map[string]string {
	merged := make(map[string]string, len(existing)+len(built))
	for k, v := range existing {
		if !strings.HasPrefix(k, tcOwnedLabelPrefix) {
			merged[k] = v
		}
	}
	for k, v := range built {
		merged[k] = v
	}
	if len(merged) == 0 {
		return nil
	}
	return merged
}

// publishDeviceClass creates or updates a DeviceClass. Updates are
// merge-preserving (foreign labels/annotations are kept, only TC-owned keys
// are added/overwritten/removed) and skipped entirely when nothing TC owns
// has changed, so a steady-state cluster produces no DeviceClass API calls.
func (m *DeviceClassManager) publishDeviceClass(ctx context.Context, dc *resourcev1.DeviceClass) error {
	existing, err := m.client.ResourceV1().DeviceClasses().Get(ctx, dc.Name, metav1.GetOptions{})
	if errors.IsNotFound(err) {
		_, err = m.client.ResourceV1().DeviceClasses().Create(ctx, dc, metav1.CreateOptions{})
		if err != nil {
			return fmt.Errorf("failed to create DeviceClass %s: %w", dc.Name, err)
		}
		klog.Infof("Created DeviceClass %s", dc.Name)
		return nil
	}
	if err != nil {
		return fmt.Errorf("failed to get DeviceClass %s: %w", dc.Name, err)
	}

	merged := existing.DeepCopy()
	merged.Spec = dc.Spec
	merged.Labels = mergeTCOwnedMetadata(existing.Labels, dc.Labels)
	merged.Annotations = mergeTCOwnedMetadata(existing.Annotations, dc.Annotations)

	if apiequality.Semantic.DeepEqual(merged.Spec, existing.Spec) &&
		stringMapEqual(merged.Labels, existing.Labels) &&
		stringMapEqual(merged.Annotations, existing.Annotations) {
		return nil
	}

	err = retry.RetryOnConflict(retry.DefaultRetry, func() error {
		latest, getErr := m.client.ResourceV1().DeviceClasses().Get(ctx, dc.Name, metav1.GetOptions{})
		if getErr != nil {
			return getErr
		}
		toUpdate := latest.DeepCopy()
		toUpdate.Spec = dc.Spec
		toUpdate.Labels = mergeTCOwnedMetadata(latest.Labels, dc.Labels)
		toUpdate.Annotations = mergeTCOwnedMetadata(latest.Annotations, dc.Annotations)
		_, updateErr := m.client.ResourceV1().DeviceClasses().Update(ctx, toUpdate, metav1.UpdateOptions{})
		return updateErr
	})
	if err != nil {
		return fmt.Errorf("failed to update DeviceClass %s: %w", dc.Name, err)
	}
	klog.Infof("Updated DeviceClass %s", dc.Name)
	return nil
}
